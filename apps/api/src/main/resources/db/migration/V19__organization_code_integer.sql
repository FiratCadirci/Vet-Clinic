-- Organizasyon kodu metinden tam sayıya (identity, 1001'den başlar) çevrilir.
-- Mevcut kayıtlar identity ile otomatik numaralandırılır; eski metin kod kaldırılır.
DROP FUNCTION IF EXISTS vet.resolve_organization_by_code(text);
DROP FUNCTION IF EXISTS vet.resolve_login_candidates(text, text);
DROP FUNCTION IF EXISTS vet.list_active_organizations();
DROP INDEX IF EXISTS vet.ux_organizations_code_lower;

ALTER TABLE vet.organizations RENAME COLUMN code TO code_legacy;
ALTER TABLE vet.organizations ADD COLUMN code integer GENERATED BY DEFAULT AS IDENTITY (START WITH 1001);
ALTER TABLE vet.organizations ADD CONSTRAINT uq_organizations_code UNIQUE (code);
ALTER TABLE vet.organizations DROP COLUMN code_legacy;

CREATE OR REPLACE FUNCTION vet.resolve_organization_by_code(p_code integer)
RETURNS uuid
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = vet, pg_temp
AS $$
    SELECT o.id
      FROM vet.organizations o
     WHERE o.code = p_code
       AND o.is_active = true
     LIMIT 1;
$$;

REVOKE ALL ON FUNCTION vet.resolve_organization_by_code(integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION vet.resolve_organization_by_code(integer) TO vet_app;

CREATE OR REPLACE FUNCTION vet.resolve_login_candidates(p_email text, p_organization_code integer DEFAULT NULL)
RETURNS TABLE (
    organization_id   uuid,
    organization_code integer,
    organization_name text,
    user_id           uuid,
    is_client         boolean
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = vet, pg_temp
AS $$
    SELECT o.id,
           o.code,
           o.name::text,
           u.id,
           EXISTS (
               SELECT 1
                 FROM vet.clients c
                WHERE c.organization_id = u.organization_id
                  AND c.app_user_id = u.id
           )
      FROM vet.app_users u
      JOIN vet.organizations o ON o.id = u.organization_id
     WHERE lower(u.email) = lower(btrim(p_email))
       AND o.is_active = true
       AND (p_organization_code IS NULL OR o.code = p_organization_code)
     ORDER BY o.code
     LIMIT 20;
$$;

REVOKE ALL ON FUNCTION vet.resolve_login_candidates(text, integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION vet.resolve_login_candidates(text, integer) TO vet_app;

CREATE OR REPLACE FUNCTION vet.list_active_organizations()
RETURNS TABLE (
    organization_code integer,
    organization_name text
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = vet, pg_temp
AS $$
    SELECT o.code, o.name::text
      FROM vet.organizations o
     WHERE o.is_active = true
     ORDER BY o.name, o.code;
$$;

REVOKE ALL ON FUNCTION vet.list_active_organizations() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION vet.list_active_organizations() TO vet_app;
